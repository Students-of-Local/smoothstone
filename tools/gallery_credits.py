"""Write failures/gallery/CREDITS.md from failures/gallery/labels.jsonl.

uv run python tools/gallery_credits.py           rewrite CREDITS.md
uv run python tools/gallery_credits.py --check   exit 1 when CREDITS.md is out of date

LICENSES is the one allowlist the gallery takes: a photo under any other license stays out.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GALLERY = ROOT / "failures" / "gallery"
LABELS = GALLERY / "labels.jsonl"
CREDITS = GALLERY / "CREDITS.md"
TAXONOMY = ROOT / "src" / "smoothstone" / "failures" / "taxonomy.json"
REPO_LICENSE = "https://github.com/Students-of-Local/smoothstone/blob/main/LICENSE"

# license name as written in labels.jsonl -> its legal text
LICENSES = {
    "CC0 1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
    "Public domain": "https://creativecommons.org/publicdomain/mark/1.0/",
    "CC BY 2.0": "https://creativecommons.org/licenses/by/2.0/",
    "CC BY 3.0": "https://creativecommons.org/licenses/by/3.0/",
    "CC BY 4.0": "https://creativecommons.org/licenses/by/4.0/",
    "CC BY-SA 2.0": "https://creativecommons.org/licenses/by-sa/2.0/",
    "CC BY-SA 3.0": "https://creativecommons.org/licenses/by-sa/3.0/",
    "CC BY-SA 4.0": "https://creativecommons.org/licenses/by-sa/4.0/",
    "MIT": REPO_LICENSE,
}
HEALTHY = "healthy"  # a print going fine; not a failure id, kept so agents can compare


def failure_ids():
    return set(json.loads(TAXONOMY.read_text())["ids"])


def load(path=LABELS):
    return [json.loads(l) for l in path.read_text().splitlines() if l.strip()]


def render(labels):
    out = [
        "# Gallery credits",
        "",
        "Generated by `tools/gallery_credits.py` from `labels.jsonl`; do not edit by hand.",
        "Every photo here was resized to at most 768 px on its long side and re-saved as JPEG with its",
        "metadata removed. Nothing else was changed. Synthetic frames are renders, not photos.",
        "",
    ]
    for group in sorted({l["failure"] for l in labels}):
        out += [f"## {group}", ""]
        for l in sorted((l for l in labels if l["failure"] == group), key=lambda l: l["file"]):
            lic = f"[{l['license']}]({LICENSES.get(l['license'], '')})"
            title = l.get("title") or Path(l["file"]).stem
            src = f"[source]({l['url']})" if l.get("url") else l["source"]
            kind = "synthetic render" if l.get("synthetic") else "resized"
            out.append(f"- `{l['file']}`: \"{title}\" by {l['author']}, {lic}, {src} ({l['source']}), {kind}.")
        out.append("")
    return "\n".join(out)


def main():
    text = render(load())
    if "--check" in sys.argv:
        if not CREDITS.exists() or CREDITS.read_text() != text:
            print("CREDITS.md is out of date: run uv run python tools/gallery_credits.py")
            return 1
        print("CREDITS.md matches labels.jsonl")
        return 0
    CREDITS.write_text(text)
    print(f"wrote {CREDITS.relative_to(ROOT)} ({len(load())} photos)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
